#!/usr/bin/env swift
// LB-413: original geometry, shared by the native vector and raster exports.
// Run from the repository root on macOS: swift scripts/generate-app-icons.swift [--check].
import AppKit

let root = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
let checking = CommandLine.arguments.contains("--check")
let red = CGColor(srgbRed: 194 / 255, green: 22 / 255, blue: 50 / 255, alpha: 1)
let white = CGColor(gray: 1, alpha: 1)
let body = CGMutablePath()
func rounded(_ path: CGMutablePath, _ x: CGFloat, _ y: CGFloat,
             _ width: CGFloat, _ height: CGFloat, _ radius: CGFloat) {
    path.addRoundedRect(in: CGRect(x: x, y: y, width: width, height: height),
                        cornerWidth: radius, cornerHeight: radius)
}
// The glyph stays inside Android's centred 66 dp diameter safe circle.
rounded(body, 31, 28, 46, 46, 8)
rounded(body, 44, 32, 20, 3, 1.5)
rounded(body, 35, 39, 38, 20, 4)
body.addEllipse(in: CGRect(x: 36.5, y: 63.5, width: 5, height: 5))
body.addEllipse(in: CGRect(x: 66.5, y: 63.5, width: 5, height: 5))
let wheels = CGMutablePath()
rounded(wheels, 35, 70, 7, 10, 2.5)
rounded(wheels, 66, 70, 7, 10, 2.5)
let divider = CGMutablePath()
divider.addRect(CGRect(x: 53, y: 39, width: 2, height: 20))
let parts: [CGPath] = [body, wheels, divider]

func pathData(_ path: CGPath) -> String {
    var commands: [String] = []
    func point(_ point: CGPoint) -> String {
        String(format: "%.3f,%.3f", locale: Locale(identifier: "en_US_POSIX"),
               Double(point.x), Double(point.y))
    }
    path.applyWithBlock { pointer in
        let element = pointer.pointee
        switch element.type {
        case .moveToPoint: commands.append("M" + point(element.points[0]))
        case .addLineToPoint: commands.append("L" + point(element.points[0]))
        case .addQuadCurveToPoint:
            commands.append("Q" + point(element.points[0]) + " " + point(element.points[1]))
        case .addCurveToPoint:
            commands.append("C" + (0..<3).map { point(element.points[$0]) }.joined(separator: " "))
        case .closeSubpath: commands.append("Z")
        @unknown default: fatalError("Unsupported path element")
        }
    }
    return commands.joined(separator: " ")
}

var outputs: [String: Data] = [:]
func text(_ path: String, _ value: String) { outputs[path] = Data((value + "\n").utf8) }
let android = "android/app/src/main/res"
let paths = parts.map(pathData)
let vectorPaths = paths.map {
    "    <path android:fillColor=\"#FFFFFFFF\" android:fillType=\"evenOdd\" android:pathData=\"\($0)\" />"
}.joined(separator: "\n")
text("\(android)/drawable/ic_launcher_foreground.xml", """
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-app-icons.swift; the cutouts are transparent for themed icons. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
\(vectorPaths)
</vector>
""")
text("\(android)/values/ic_launcher_background.xml", """
<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Logrono municipal identity manual, page 18: Pantone 200 C. -->
    <color name="ic_launcher_background">#C21632</color>
</resources>
""")
for (folder, monochrome) in [("mipmap-anydpi-v26", false), ("mipmap-anydpi-v33", true)] {
    let themed = monochrome ? "\n    <monochrome android:drawable=\"@drawable/ic_launcher_foreground\" />" : ""
    text("\(android)/\(folder)/ic_launcher.xml", """
    <?xml version="1.0" encoding="utf-8"?>
    <adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
        <background android:drawable="@color/ic_launcher_background" />
        <foreground android:drawable="@drawable/ic_launcher_foreground" />\(themed)
    </adaptive-icon>
    """)
}
let svgPaths = paths.map { "  <path fill-rule=\"evenodd\" d=\"\($0)\"/>" }.joined(separator: "\n")
text("assets/branding/bus.svg", """
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" fill="white">
\(svgPaths)
</svg>
""")

func png(appearance: String) throws -> Data {
    let size = 1024
    let transparent = appearance == "dark"
    let alpha = transparent ? CGImageAlphaInfo.premultipliedLast : .noneSkipLast
    guard let space = CGColorSpace(name: CGColorSpace.sRGB),
          let context = CGContext(data: nil, width: size, height: size, bitsPerComponent: 8,
                                  bytesPerRow: size * 4, space: space, bitmapInfo: alpha.rawValue)
    else { fatalError("Cannot create the sRGB icon context") }
    context.scaleBy(x: CGFloat(size) / 108, y: CGFloat(size) / 108)
    // Match SVG's top-left origin; iOS masking is applied by the system, never baked in.
    context.translateBy(x: 0, y: 108)
    context.scaleBy(x: 1, y: -1)
    if !transparent {
        context.setFillColor(appearance == "tinted" ? CGColor(gray: 0.12, alpha: 1) : red)
        context.fill(CGRect(x: 0, y: 0, width: 108, height: 108))
    }
    context.translateBy(x: 54, y: 54)
    context.scaleBy(x: 1.25, y: 1.25)
    context.translateBy(x: -54, y: -54)
    context.setFillColor(transparent ? CGColor(srgbRed: 1, green: 0.32, blue: 0.43, alpha: 1) : white)
    for part in parts {
        context.addPath(part)
        context.drawPath(using: .eoFill)
    }
    guard let image = context.makeImage(),
          let data = NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])
    else { fatalError("Cannot encode the icon PNG") }
    return data
}
let catalog = "iosApp/iosApp/Assets.xcassets"
text("\(catalog)/Contents.json", """
{"info":{"author":"xcode","version":1}}
""")
let iconSet = "\(catalog)/AppIcon.appiconset"
var images: [[String: Any]] = []
for appearance in ["any", "dark", "tinted"] {
    let filename = "AppIcon-\(appearance).png"
    outputs["\(iconSet)/\(filename)"] = try png(appearance: appearance)
    var entry: [String: Any] = ["filename": filename, "idiom": "universal",
                                "platform": "ios", "size": "1024x1024"]
    if appearance != "any" { entry["appearances"] = [["appearance": "luminosity", "value": appearance]] }
    images.append(entry)
}
outputs["\(iconSet)/Contents.json"] = try JSONSerialization.data(
    withJSONObject: ["images": images, "info": ["author": "xcode", "version": 1]],
    options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]) + Data("\n".utf8)

var mismatches: [String] = []
for path in outputs.keys.sorted() {
    let url = root.appendingPathComponent(path)
    guard let data = outputs[path] else { continue }
    if checking {
        if (try? Data(contentsOf: url)) != data { mismatches.append(path) }
    } else {
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(),
                                                withIntermediateDirectories: true)
        try data.write(to: url, options: .atomic)
    }
}
if !mismatches.isEmpty {
    fatalError("Icon exports need regeneration: \(mismatches.joined(separator: ", "))")
}
print("OK: \(outputs.count) native icon resources \(checking ? "match their source" : "generated")")
